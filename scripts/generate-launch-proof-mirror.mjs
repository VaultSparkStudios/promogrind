#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "context", "LAUNCH_PROOFS.json");
const OUT = join(ROOT, "src", "data", "launchProofs.generated.js");

function readProofs() {
  try {
    return JSON.parse(readFileSync(SOURCE, "utf8"));
  } catch {
    return {
      schemaVersion: "1.0",
      lastUpdated: null,
      proofs: {},
    };
  }
}

const payload = readProofs();
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  [
    "// Generated by scripts/generate-launch-proof-mirror.mjs.",
    "// Do not edit by hand; update context/LAUNCH_PROOFS.json instead.",
    `export const LAUNCH_PROOFS = ${JSON.stringify(payload, null, 2)};`,
    "",
  ].join("\n"),
);

console.log(`launch-proof-mirror: wrote ${OUT.replace(ROOT + "\\", "").replace(/\\/g, "/")}`);
