#!/usr/bin/env node
/**
 * studio-narrator.mjs — Daily studio narrative (v3.1)
 *
 * Reads the last 24h of Studio Pulse events + current project snapshots +
 * the Founder Queue, and produces a 3-5 sentence natural-language narrative
 * at `portfolio/STUDIO_NARRATIVE.md`. Uses Haiku for cheap daily runs.
 *
 * When `ANTHROPIC_API_KEY` is not available, writes a deterministic
 * template-based narrative from the event stream (no API call).
 *
 * Usage:
 *   node scripts/studio-narrator.mjs
 *   node scripts/studio-narrator.mjs --dry-run    # prints narrative, skips write
 */

import fs from 'fs';
import path from 'path';
import https from 'https';
import { fileURLToPath } from 'url';
import { MODELS, callClaude, withLongCache, logMetrics } from './lib/model-router.mjs';
import { getSecret } from './lib/secrets.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const NDJSON = path.join(ROOT, 'portfolio', 'STUDIO_PULSE.ndjson');
const OUT    = path.join(ROOT, 'portfolio', 'STUDIO_NARRATIVE.md');
const STATE_DIR = path.join(ROOT, '.ops-cache', 'pulse-state.json');

const dry = process.argv.includes('--dry-run');

function readJson(p, fb) { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fb; } }

// Gather last 24h of events
const cutoff = Date.now() - 86400_000;
let events = [];
try {
  events = fs.readFileSync(NDJSON, 'utf8').split(/\r?\n/).filter(Boolean)
    .map(l => { try { return JSON.parse(l); } catch { return null; } })
    .filter(Boolean)
    .filter(e => new Date(e.ts).getTime() >= cutoff);
} catch {}

const state = readJson(STATE_DIR, { snapshots: {} });
const projects = Object.values(state.snapshots || {});
const health = projects.reduce((m, p) => { m[p.health || 'unknown'] = (m[p.health || 'unknown'] || 0) + 1; return m; }, {});

// ── Deterministic fallback narrative (no API needed) ─────────────────────────
function templateNarrative() {
  const types = events.reduce((m, e) => { m[e.type] = (m[e.type] || 0) + 1; return m; }, {});
  const top = Object.entries(types).sort((a, b) => b[1] - a[1]).slice(0, 3);
  const topStr = top.map(([t, n]) => `${n}× ${t}`).join(', ') || 'no notable events';
  const health_line = `${health.green || 0} green / ${health.yellow || 0} yellow / ${health.red || 0} red`;
  return `Studio observed ${projects.length} projects today — ${health_line}. Last 24h surfaced ${events.length} events (${topStr}). Portfolio average SIL is steady. Founder Queue is the right lens if any of these need attention.`;
}

// ── LLM-enhanced narrative (Haiku) ───────────────────────────────────────────
async function llmNarrative() {
  const apiKey = getSecret('ANTHROPIC_API_KEY', 'claude.api');
  if (!apiKey) return templateNarrative();

  const systemStable = withLongCache({
    type: 'text',
    text: `You are the Studio Narrator for VaultSpark Studios. Write one short paragraph (3-5 sentences) summarizing the studio's past 24 hours in a concrete, factual, slightly literary voice. No emojis. No bullet points. No headers. Refer to specific projects and event types by name. End with a one-sentence pointer at what to watch tomorrow.`,
  });

  const userText = `Snapshot:\n- ${projects.length} projects tracked\n- Health mix: ${JSON.stringify(health)}\n\nEvents (last 24h):\n${events.slice(0, 40).map(e => `- ${e.slug}: ${e.type} (${e.severity}) — ${JSON.stringify(e.detail || {})}`).join('\n') || '(none)'}\n\nProject snapshots:\n${projects.slice(0, 25).map(p => `- ${p.slug}: SIL ${p.silScore || '?'} · IGNIS ${p.ignisScore || '?'} · health ${p.health || '?'}`).join('\n')}`;

  try {
    const resp = await callClaude({
      apiKey,
      model: MODELS.haiku,
      maxTokens: 400,
      system: [systemStable],
      messages: [{ role: 'user', content: userText }],
    }, https);
    logMetrics({ script: 'studio-narrator', model: MODELS.haiku, usage: resp.usage, mode: 'daily' });
    const text = resp.content?.map(c => c.text || '').join('') || '';
    return text.trim() || templateNarrative();
  } catch (e) {
    process.stderr.write(`narrator fallback: ${e.message}\n`);
    return templateNarrative();
  }
}

const narrative = await llmNarrative();
const today = new Date().toISOString().slice(0, 10);
const md = `<!-- generated-by: scripts/studio-narrator.mjs v3.1 -->\n<!-- generated-at: ${new Date().toISOString()} -->\n\n# Studio Narrative — ${today}\n\n${narrative}\n\n---\n\n*Generated by \`scripts/studio-narrator.mjs\`. Re-run daily (cron) or via \`ops narrator\`.*\n`;

if (dry) {
  console.log(md);
} else {
  fs.writeFileSync(OUT, md);
  console.log(`✓ Studio Narrative → portfolio/STUDIO_NARRATIVE.md`);
}
