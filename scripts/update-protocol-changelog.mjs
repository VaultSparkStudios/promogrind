#!/usr/bin/env node
/**
 * update-protocol-changelog.mjs
 *
 * Auto-appends an entry to docs/PROTOCOL_CHANGELOG.md whenever
 * prompt or template files changed this session (detected via git diff).
 * Safe to run every closeout — no-ops if no relevant changes detected.
 *
 * Usage:
 *   node scripts/update-protocol-changelog.mjs
 *   node scripts/update-protocol-changelog.mjs --session N --summary "description"
 *   node scripts/ops.mjs protocol-changelog
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { spawnSync } from 'child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT  = path.join(ROOT, 'docs', 'PROTOCOL_CHANGELOG.md');

function readText(p) { try { return fs.readFileSync(p, 'utf8'); } catch { return ''; } }
function readJson(p, fb) { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fb; } }

const today   = new Date().toISOString().slice(0, 10);
const status  = readJson(path.join(ROOT, 'context', 'PROJECT_STATUS.json'), {});
const session = (() => {
  const idx = process.argv.indexOf('--session');
  return idx !== -1 ? parseInt(process.argv[idx + 1]) : status.currentSession ?? 63;
})();
const manualSummary = (() => {
  const idx = process.argv.indexOf('--summary');
  return idx !== -1 ? process.argv[idx + 1] : null;
})();

// ── Detect changed protocol files via git diff ────────────────────────────────
const TRACKED_PATTERNS = [
  'prompts/start.md',
  'prompts/closeout.md',
  'prompts/initiate.md',
  'prompts/studio-review.md',
  'docs/templates/project-system/',
  'AGENTS.md',
  'CLAUDE.md',
];

function getChangedFiles() {
  const res = spawnSync('git', ['-C', ROOT, 'diff', '--name-only', 'HEAD'], { encoding: 'utf8' });
  const staged = spawnSync('git', ['-C', ROOT, 'diff', '--name-only', '--cached'], { encoding: 'utf8' });
  const all = [(res.stdout ?? ''), (staged.stdout ?? '')].join('\n')
    .split(/\r?\n/).map(l => l.trim()).filter(Boolean);
  return [...new Set(all)];
}

const changedFiles = getChangedFiles();
const protocolChanged = changedFiles.filter(f =>
  TRACKED_PATTERNS.some(p => f.startsWith(p) || f === p)
);

// Also detect committed-since-last-tag changes if no uncommitted changes found
function getCommittedChanges() {
  const res = spawnSync('git', ['-C', ROOT, 'show', '--name-only', '--format=', 'HEAD'], { encoding: 'utf8' });
  return (res.stdout ?? '').split(/\r?\n/).map(l => l.trim()).filter(Boolean);
}

const relevantChanged = protocolChanged.length > 0
  ? protocolChanged
  : getCommittedChanges().filter(f => TRACKED_PATTERNS.some(p => f.startsWith(p) || f === p));

if (relevantChanged.length === 0 && !manualSummary) {
  console.log('ℹ Protocol changelog: no prompt/template files changed — no entry added.');
  process.exit(0);
}

// ── Extract version numbers ───────────────────────────────────────────────────
function extractVersion(filePath) {
  const content = readText(path.join(ROOT, filePath));
  return content.match(/template-version:\s*([\d.]+)/)?.[1] ?? null;
}

const startVer    = extractVersion('prompts/start.md');
const closeoutVer = extractVersion('prompts/closeout.md');
const startTplVer = extractVersion('docs/templates/project-system/START_PROMPT.template.md');

// ── Build entry ───────────────────────────────────────────────────────────────
const fileList = relevantChanged.map(f => `\`${f}\``).join(', ');
const versionNote = startVer ? `Template version: v${startVer}${startTplVer && startTplVer !== startVer ? ` (template: v${startTplVer})` : ''}` : '';

const summary = manualSummary ?? (() => {
  const changes = [];
  if (relevantChanged.some(f => f.includes('start.md') || f.includes('START_PROMPT'))) changes.push('start prompt updated');
  if (relevantChanged.some(f => f.includes('closeout.md') || f.includes('CLOSEOUT_PROMPT'))) changes.push('closeout prompt updated');
  if (relevantChanged.some(f => f.includes('initiate.md'))) changes.push('initiate prompt updated');
  if (relevantChanged.some(f => f.includes('AGENTS.md'))) changes.push('AGENTS.md updated');
  if (relevantChanged.some(f => f.includes('templates/'))) changes.push('templates updated');
  return changes.length > 0 ? changes.join(' · ') : 'protocol files updated';
})();

const newEntry = [
  `## ${today} — Session ${session}`,
  ``,
  `**Summary:** ${summary}`,
  ``,
  `**Files changed:** ${fileList}`,
  ...(versionNote ? [``, `**${versionNote}**`] : []),
  ``,
  `---`,
  ``,
].join('\n');

// ── Read or create PROTOCOL_CHANGELOG.md ─────────────────────────────────────
const header = [
  `# Protocol Changelog`,
  ``,
  `_Auto-generated by \`scripts/update-protocol-changelog.mjs\` at each closeout._`,
  `_Records changes to prompt files, templates, and core protocol documents._`,
  ``,
  `---`,
  ``,
].join('\n');

let existing = readText(OUT);
if (!existing) {
  existing = header;
}

// Insert new entry after the header block (after first ---)
const insertAfter = existing.indexOf('\n---\n\n');
const updated = insertAfter !== -1
  ? existing.slice(0, insertAfter + 6) + newEntry + existing.slice(insertAfter + 6)
  : existing + '\n' + newEntry;

fs.writeFileSync(OUT, updated, 'utf8');
console.log(`✓ Protocol changelog → docs/PROTOCOL_CHANGELOG.md`);
console.log(`  Session ${session} · ${summary}`);
console.log(`  Files: ${relevantChanged.join(', ')}`);
