#!/usr/bin/env node
/**
 * render-genome-history.mjs
 *
 * Reads context/GENOME_HISTORY.json and renders docs/GENOME_HISTORY.md —
 * a markdown heatmap showing how each protocol genome dimension evolved
 * across sessions.
 *
 * Usage:
 *   node scripts/render-genome-history.mjs [--project <localPath>]
 *   node scripts/ops.mjs genome-history
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const projectIdx = process.argv.indexOf('--project');
const targetPath = projectIdx !== -1 ? path.resolve(process.argv[projectIdx + 1]) : ROOT;

function readJson(p, fb = null) {
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fb; }
}

const ctx = (f) => path.join(targetPath, 'context', f);
const history = readJson(ctx('GENOME_HISTORY.json'));

if (!history || !history.snapshots || history.snapshots.length === 0) {
  console.error('No genome history found. Run: node scripts/ops.mjs genome-snapshot');
  process.exit(1);
}

const snapshots = history.snapshots;
const dims = Object.keys(snapshots[0].dimensions);
const dimLabels = {
  schema_alignment: 'Schema alignment',
  prompt_template_alignment: 'Prompt/template alignment',
  derived_view_freshness: 'Derived-view freshness',
  handoff_continuity: 'Handoff continuity',
  contradiction_density: 'Contradiction density',
};

// Score → emoji cell
function cell(score, max = 5) {
  if (score === null || score === undefined) return '·';
  const pct = score / max;
  if (pct >= 1.0) return '🟢';
  if (pct >= 0.8) return '🟡';
  if (pct >= 0.6) return '🟠';
  return '🔴';
}

// Status → short label
function statusLabel(s) {
  if (s === 'green') return '🟢';
  if (s === 'yellow') return '🟡';
  if (s === 'red') return '🔴';
  return '·';
}

// Recent 20 snapshots for the heatmap columns
const recent = snapshots.slice(-20);
const sessionLabels = recent.map(s => `S${s.session ?? '?'}`);

// Compute trend for each dimension (last 3 snapshots)
function trend(dim) {
  const vals = snapshots.slice(-3).map(s => s.dimensions[dim] ?? null).filter(v => v !== null);
  if (vals.length < 2) return '→';
  const diff = vals.at(-1) - vals[0];
  return diff > 0 ? '↑' : diff < 0 ? '↓' : '→';
}

// Build lines
const today = new Date().toISOString().slice(0, 10);
const lines = [
  `<!-- generated-by: scripts/render-genome-history.mjs -->`,
  `<!-- generated-at: ${today} -->`,
  ``,
  `# Protocol Genome History — ${history.project || 'Studio Ops'}`,
  ``,
  `> Tracks how each truth-audit genome dimension evolved across sessions.`,
  `> 🟢 = 5/5  🟡 = 4/5  🟠 = 3/5  🔴 = 0-2/5`,
  ``,
  `---`,
  ``,
  `## Dimension Heatmap (last ${recent.length} sessions)`,
  ``,
];

// Header row
const header = `| Dimension | Trend | ${sessionLabels.join(' | ')} |`;
const divider = `|---|:---:|${sessionLabels.map(() => ':---:').join('|')}|`;
lines.push(header, divider);

for (const dim of dims) {
  const label = dimLabels[dim] || dim.replace(/_/g, ' ');
  const cells = recent.map(s => cell(s.dimensions[dim])).join(' | ');
  const t = trend(dim);
  lines.push(`| ${label} | ${t} | ${cells} |`);
}

// Overall status row
const statusCells = recent.map(s => statusLabel(s.overallStatus)).join(' | ');
lines.push(`| **Overall status** | | ${statusCells} |`);

lines.push(``, `---`, ``);

// Summary table (all snapshots)
lines.push(`## Full History`, ``);
lines.push(`| Date | Session | Total | Status | Delta | Notes |`);
lines.push(`|---|---|---|---|---|---|`);

for (const s of snapshots) {
  const delta = s.delta !== null ? (s.delta > 0 ? `+${s.delta}` : String(s.delta)) : '—';
  const cause = (s.cause ?? '').slice(0, 60);
  lines.push(`| ${s.date} | S${s.session ?? '?'} | ${s.total}/${s.maxTotal} | ${statusLabel(s.overallStatus)} ${s.overallStatus} | ${delta} | ${cause} |`);
}

lines.push(``, `---`, ``);

// Trend analysis
const totals = snapshots.map(s => s.total);
const avg = (totals.reduce((a, b) => a + b, 0) / totals.length).toFixed(1);
const peak = Math.max(...totals);
const low  = Math.min(...totals);
lines.push(`## Statistics`, ``);
lines.push(`- Sessions tracked: **${snapshots.length}**`);
lines.push(`- Average genome score: **${avg}/25**`);
lines.push(`- Peak: **${peak}/25** · Low: **${low}/25**`);
lines.push(`- Current: **${snapshots.at(-1).total}/25** (${snapshots.at(-1).overallStatus})`);
lines.push(``);
lines.push(`*Generated by \`scripts/render-genome-history.mjs\` · ${today}*`);
lines.push(``);

const outPath = path.join(targetPath, 'docs', 'GENOME_HISTORY.md');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`✓ Genome history → ${path.relative(ROOT, outPath)}`);
console.log(`  ${snapshots.length} snapshots · current ${snapshots.at(-1).total}/25 (${snapshots.at(-1).overallStatus}) · avg ${avg}/25`);
