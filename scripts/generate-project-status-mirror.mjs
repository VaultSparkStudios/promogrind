#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "context", "PROJECT_STATUS.json");
const OUT = join(ROOT, "src", "data", "projectStatus.generated.js");
const check = process.argv.includes("--check");

function compactStatus(value, verifiedAt) {
  const status = String(value || "unknown").trim();
  if (/\bpassing\b/i.test(status)) return `passing · verified ${verifiedAt || "date unknown"}`;
  return status;
}

function buildMirror(status) {
  const surfaces = Array.isArray(status.testingSurfaces) ? status.testingSurfaces : [];
  const surface = (type) => surfaces.find((item) => item?.type === type) || {};
  const verifiedAt = status.testsLastRun || status.lastUpdated || null;
  const testsPassing = Number.isFinite(status.testsPassing) ? status.testsPassing : null;
  const testsTotal = Number.isFinite(status.testsTotal) ? status.testsTotal : null;
  const testsLastKnown = testsPassing != null && testsTotal != null
    ? `${testsPassing}/${testsTotal} passing · verified ${verifiedAt || "date unknown"}`
    : compactStatus(surface("tests").status, verifiedAt);
  const launchStatus = compactStatus(surface("launch-gate").status, status.lastUpdated);

  return {
    source: "context/PROJECT_STATUS.json",
    sourceLastUpdated: status.lastUpdated || null,
    testsPassing,
    testsTotal,
    testsLastRun: status.testsLastRun || null,
    validation: {
      smokeCommand: {
        label: "Repo launch smoke",
        command: "npm run smoke:launch",
        lastKnown: launchStatus,
      },
      browserSmoke: {
        label: "Browser smoke",
        command: "npm run smoke:browser",
        lastKnown: launchStatus,
      },
      tests: {
        label: "Vitest",
        command: "npm test",
        lastKnown: testsLastKnown,
      },
      build: {
        label: "Build",
        command: "npm run build",
        lastKnown: launchStatus,
      },
    },
  };
}

const status = JSON.parse(readFileSync(SOURCE, "utf8"));
const payload = buildMirror(status);
const output = [
  "// Generated by scripts/generate-project-status-mirror.mjs.",
  "// Browser-safe allowlist only. Update context/PROJECT_STATUS.json, then regenerate.",
  `export const PROJECT_STATUS_MIRROR = ${JSON.stringify(payload, null, 2)};`,
  "",
].join("\n");

if (check) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* stale/missing */ }
  if (current !== output) {
    console.error("project-status-mirror: stale; run node scripts/generate-project-status-mirror.mjs");
    process.exit(1);
  }
  console.log("project-status-mirror: fresh");
} else {
  writeFileSync(OUT, output);
  console.log("project-status-mirror: wrote src/data/projectStatus.generated.js");
}
