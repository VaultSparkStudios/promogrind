#!/usr/bin/env node

/**
 * render-debt-report.mjs
 *
 * Generates portfolio/DEBT_REPORT.md from live project truth surfaces.
 * Replaces the old mechanical debt-score workflow with actionable intelligence:
 *   - Per-project debt signals from truth audits, contradiction counts, and staleness
 *   - Automation debt from AUTOMATION_VALUE_GATE.md
 *   - Compliance gaps and protocol drift
 *
 * Run: node scripts/render-debt-report.mjs
 * CI:  called by .github/workflows/tech-debt-watchdog.yml
 */

import fs from 'fs';
import path from 'path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'portfolio', 'PROJECT_REGISTRY.json'), 'utf8'));
const automationGate = readText(path.join(root, 'portfolio', 'AUTOMATION_VALUE_GATE.md'));
const today = new Date().toISOString().slice(0, 10);
const todayEpoch = Date.now();

const activeProjects = registry.projects.filter((p) => p.status !== 'archived');
const appliedProjects = activeProjects.filter((p) => p.studioOsApplied);
const nonCompliant = activeProjects.filter((p) => !p.studioOsApplied);

// Score each project's debt
const rows = appliedProjects.map((project) => {
  const status = readJson(path.join(project.localPath ?? '', 'context', 'PROJECT_STATUS.json'));
  const truthAudit = readText(path.join(project.localPath ?? '', 'context', 'TRUTH_AUDIT.md'));
  const contradictions = extractContradictions(truthAudit);
  const truthStatus = status?.truthAuditStatus ?? extractScalar(truthAudit, /^Overall status:\s*(.+)$/m) ?? 'unknown';
  const blockers = Array.isArray(status?.blockers) ? status.blockers : [];

  // Staleness: days since lastUpdated
  const lastUpdated = status?.lastUpdated ? new Date(status.lastUpdated) : null;
  const daysSince = lastUpdated ? Math.floor((todayEpoch - lastUpdated.getTime()) / 86400000) : null;

  // Debt score (0–100)
  let debt = 0;
  if (truthStatus === 'red') debt += 25;
  else if (truthStatus === 'yellow') debt += 10;
  debt += Math.min(contradictions.length, 5) * 5; // up to 25
  debt += Math.min(blockers.length, 3) * 8;       // up to 24
  if (daysSince != null && daysSince > 14) debt += 10;
  if (daysSince != null && daysSince > 30) debt += 10;
  debt = Math.min(debt, 100);

  return {
    name: project.name,
    slug: project.slug,
    health: status?.health ?? project.health ?? 'unknown',
    truthStatus,
    contradictionCount: contradictions.length,
    blockerCount: blockers.length,
    daysSince,
    debt,
    topContradiction: contradictions[0] ?? null,
    topBlocker: blockers[0] ?? null,
  };
}).sort((a, b) => b.debt - a.debt);

// Automation debt
const automationRows = extractAutomationRows(automationGate);
const rebuildRows = automationRows.filter((r) => r.status === 'rebuild');

// Portfolio debt stats
const avgDebt = average(rows.map((r) => r.debt));
const highDebt = rows.filter((r) => r.debt > 40);
const totalContradictions = rows.reduce((s, r) => s + r.contradictionCount, 0);

const lines = [
  '# Technical Debt Report',
  '',
  `Generated by \`scripts/render-debt-report.mjs\` from live project truth surfaces.`,
  `Purpose: surface actionable technical and protocol debt across the portfolio.`,
  '',
  '---',
  '',
  `## ${today} — Debt Assessment`,
  '',
  '### Portfolio Debt Summary',
  '',
  `> Avg debt score: **${fmt(avgDebt, 0)}/100** | High-debt projects (>40): **${highDebt.length}** | `,
  `> Total contradictions: **${totalContradictions}** | Non-compliant repos: **${nonCompliant.length}** | `,
  `> Automation surfaces needing rebuild: **${rebuildRows.length}**`,
  '',
  '### Per-Project Debt Scores',
  '',
  '| Project | Debt | Health | Truth | Contradictions | Blockers | Stale (days) | Top Issue |',
  '|---|---:|---|---|---:|---:|---:|---|',
  ...rows.map((r) =>
    `| ${r.name} | ${r.debt}/100 | ${r.health} | ${r.truthStatus} | ${r.contradictionCount} | ${r.blockerCount} | ${r.daysSince ?? '—'} | ${truncate(r.topContradiction ?? r.topBlocker ?? 'none', 60)} |`
  ),
  '',
  '### Non-Compliant Projects',
  '',
  ...(nonCompliant.length
    ? nonCompliant.map((p) => `- **${p.name}** (${p.slug}) — Studio OS not applied; lifecycle: ${p.lifecycle ?? '—'}`)
    : ['- All active projects are Studio OS compliant.']),
  '',
  '### Automation Debt',
  '',
  ...(rebuildRows.length
    ? rebuildRows.map((r) => `- **${r.surface}** — status: ${r.status}; signals: ${r.signals || '—'}`)
    : ['- No automation surfaces flagged for rebuild.']),
  '',
  '### Recommended Actions',
  '',
  ...buildActions({ highDebt, nonCompliant, rebuildRows, totalContradictions }),
  '',
  '---',
  '',
  `*Generated: ${today} | Source: PROJECT_STATUS.json + TRUTH_AUDIT.md per repo + AUTOMATION_VALUE_GATE.md*`,
  '',
];

fs.writeFileSync(path.join(root, 'portfolio', 'DEBT_REPORT.md'), lines.join('\n'));
console.log(`DEBT_REPORT.md written (${rows.length} projects scored, ${today})`);

// ── Helpers ────────────────────────────────────────────────────────────────

function readJson(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return null;
  try { return JSON.parse(fs.readFileSync(filePath, 'utf8')); } catch { return null; }
}

function readText(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return '';
  return fs.readFileSync(filePath, 'utf8');
}

function extractScalar(md, pattern) {
  return md.match(pattern)?.[1]?.trim() ?? null;
}

function extractContradictions(md) {
  const section = md.match(/## Contradictions\s+([\s\S]*?)(?=\n##\s+|$)/);
  if (!section) return [];
  return section[1].split(/\r?\n/).map((l) => l.trim()).filter((l) => l.startsWith('- ') && !/^none recorded/i.test(l.slice(2)));
}

function extractAutomationRows(md) {
  return md.split(/\r?\n/)
    .filter((l) => l.startsWith('|') && !l.includes('---') && !l.includes('Surface | Status'))
    .map((l) => l.split('|').map((c) => c.trim()).filter(Boolean))
    .filter((c) => c.length >= 5)
    .map(([surface, status, freshness, signals, why]) => ({ surface, status, freshness, signals, why }));
}

function average(vals) { return vals.length ? vals.reduce((s, v) => s + v, 0) / vals.length : null; }
function fmt(v, d = 0) { return v == null ? '—' : Number(v).toFixed(d); }
function truncate(s, max) { return s.length > max ? s.slice(0, max - 1) + '...' : s; }

function buildActions({ highDebt, nonCompliant, rebuildRows, totalContradictions }) {
  const actions = [];
  if (highDebt.length) actions.push(`1. Address highest-debt project: **${highDebt[0].name}** (${highDebt[0].debt}/100) — ${highDebt[0].topContradiction ?? highDebt[0].topBlocker ?? 'review truth audit'}.`);
  if (nonCompliant.length) actions.push(`${actions.length + 1}. Bring ${nonCompliant.length} non-compliant project(s) onto Studio OS: ${nonCompliant.map((p) => p.name).join(', ')}.`);
  if (totalContradictions > 5) actions.push(`${actions.length + 1}. Reduce contradiction debt (${totalContradictions} total) — run truth-audit normalization passes on worst projects.`);
  if (rebuildRows.length) actions.push(`${actions.length + 1}. Complete automation rebuild: ${rebuildRows.map((r) => r.surface).join(', ')}.`);
  if (!actions.length) actions.push('1. Portfolio debt is low — maintain current hygiene.');
  return actions;
}
