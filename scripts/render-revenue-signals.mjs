#!/usr/bin/env node

/**
 * render-revenue-signals.mjs
 *
 * Generates portfolio/REVENUE_SIGNALS.md from live project truth surfaces.
 * Replaces the never-implemented Revenue Scout with a truth-backed assessment:
 *   - Revenue readiness per project based on lifecycle, audience, and deployment status
 *   - Funding readiness signals from project focus and milestones
 *   - Monetization pipeline sorted by proximity to revenue
 *
 * Run: node scripts/render-revenue-signals.mjs
 */

import fs from 'fs';
import path from 'path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const registryPath = path.join(root, 'portfolio', 'PROJECT_REGISTRY.json');
const statusPath = path.join(root, 'context', 'PROJECT_STATUS.json');
const manifestPath = path.join(root, 'context', 'STUDIO_MANIFEST.json');
const today = new Date().toISOString().slice(0, 10);
const registry = readJson(registryPath);
const status = readJson(statusPath) || {};
const manifest = readJson(manifestPath) || {};
const activeProjects = registry?.projects?.filter((p) => p.status !== 'archived') || [buildLocalProject(status, manifest)];
const isPortfolioMode = !!registry?.projects?.length;

// Revenue readiness scoring
const rows = activeProjects.map((project) => {
  const status = readJson(path.join(project.localPath ?? '', 'context', 'PROJECT_STATUS.json'));

  // Revenue readiness score (0–10)
  let readiness = 0;
  const lifecycle = project.lifecycle ?? 'concept';
  const audience = project.audience ?? 'internal';
  const medium = project.medium ?? '';
  const type = project.type ?? [];

  // Lifecycle scoring
  if (lifecycle === 'deployed' || lifecycle === 'mature') readiness += 3;
  else if (lifecycle === 'building') readiness += 1;

  // Audience scoring
  if (audience === 'public-traction') readiness += 3;
  else if (audience === 'public-live') readiness += 2;
  else if (audience === 'public-unlaunched') readiness += 1;

  // Medium scoring — products closer to money
  if (['game', 'platform', 'tool', 'app'].includes(medium)) readiness += 1;
  if (Array.isArray(type) && (type.includes('saas') || type.includes('crypto') || type.includes('dashboard'))) readiness += 1;

  // Has runtime URL = deployed somewhere
  if (project.runtimeUrl) readiness += 1;

  // Has monetization keywords in focus/milestone
  const text = `${project.currentFocus ?? ''} ${project.nextMilestone ?? ''} ${project.summary ?? ''}`.toLowerCase();
  if (/stripe|payment|subscription|revenue|monetiz|affiliate|freemium|premium/.test(text)) readiness += 1;

  readiness = Math.min(readiness, 10);

  // Revenue stage classification
  let stage;
  if (readiness >= 7) stage = 'revenue-ready';
  else if (readiness >= 4) stage = 'pre-revenue';
  else if (readiness >= 2) stage = 'early-build';
  else stage = 'concept';

  return {
    name: project.name,
    slug: project.slug,
    medium,
    lifecycle,
    audience,
    readiness,
    stage,
    health: status?.health ?? project.health ?? 'unknown',
    focus: status?.currentFocus ?? project.currentFocus ?? '—',
    milestone: status?.nextMilestone ?? project.nextMilestone ?? '—',
    runtimeUrl: project.runtimeUrl ?? '',
    silScore: num(status?.silScore),
    ignisScore: num(status?.ignisScore),
  };
}).sort((a, b) => b.readiness - a.readiness);

// Pipeline breakdown
const revenueReady = rows.filter((r) => r.stage === 'revenue-ready');
const preRevenue = rows.filter((r) => r.stage === 'pre-revenue');
const earlyBuild = rows.filter((r) => r.stage === 'early-build');
const concept = rows.filter((r) => r.stage === 'concept');

const lines = [
  '# Revenue Signals',
  '',
  `Generated by \`scripts/render-revenue-signals.mjs\` from live project truth surfaces.`,
  `Purpose: surface revenue readiness and monetization pipeline for studio strategy.`,
  '',
  '---',
  '',
  `## ${today} — Revenue Readiness Assessment`,
  '',
  '### Pipeline Summary',
  '',
  `> Revenue-ready (7+): **${revenueReady.length}** | Pre-revenue (4-6): **${preRevenue.length}** | `,
  `> Early-build (2-3): **${earlyBuild.length}** | Concept (0-1): **${concept.length}** | `,
  `> Total active: **${rows.length}**`,
  '',
  '### Revenue Readiness Scores',
  '',
  '| Project | Readiness | Stage | Lifecycle | Audience | Medium | Health | Next Milestone |',
  '|---|---:|---|---|---|---|---|---|',
  ...rows.map((r) =>
    `| ${r.name} | ${r.readiness}/10 | ${r.stage} | ${r.lifecycle} | ${r.audience} | ${r.medium} | ${r.health} | ${truncate(r.milestone, 50)} |`
  ),
  '',
  '### Revenue-Ready Projects (score 7+)',
  '',
  ...(revenueReady.length
    ? revenueReady.map((r) => `- **${r.name}** (${r.readiness}/10) — ${r.focus}`)
    : ['- No projects have reached revenue-ready status yet.']),
  '',
  '### Pre-Revenue Pipeline (score 4-6)',
  '',
  ...(preRevenue.length
    ? preRevenue.map((r) => `- **${r.name}** (${r.readiness}/10) — ${truncate(r.milestone, 80)}`)
    : ['- No pre-revenue projects.']),
  '',
  '### Funding Readiness',
  '',
  '| Signal | Status |',
  '|---|---|',
  `| Projects with live runtime | ${rows.filter((r) => r.runtimeUrl).length} |`,
  `| Public-facing products | ${rows.filter((r) => r.audience.startsWith('public')).length} |`,
  `| Deployed + public products | ${rows.filter((r) => r.lifecycle === 'deployed' && r.audience.startsWith('public')).length} |`,
  `| Products mentioning monetization | ${rows.filter((r) => /stripe|payment|subscription|revenue|monetiz|affiliate|freemium|premium/.test(`${r.focus} ${r.milestone}`.toLowerCase())).length} |`,
  '',
  '### Recommended Actions',
  '',
  ...buildActions({ revenueReady, preRevenue, rows }),
  '',
  '---',
  '',
  `*Generated: ${today} | Source: PROJECT_REGISTRY.json + PROJECT_STATUS.json per repo*`,
  '',
];

const outPath = isPortfolioMode
  ? path.join(root, 'portfolio', 'REVENUE_SIGNALS.md')
  : path.join(root, 'docs', 'REVENUE_SIGNALS.md');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`REVENUE_SIGNALS.md written (${rows.length} project${rows.length === 1 ? '' : 's'} scored, ${today}) → ${path.relative(root, outPath).replace(/\\/g, '/')}`);

// ── Helpers ────────────────────────────────────────────────────────────────

function readJson(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return null;
  try { return JSON.parse(fs.readFileSync(filePath, 'utf8')); } catch { return null; }
}

function num(v) { const n = Number(v); return Number.isFinite(n) ? n : null; }
function truncate(s, max) { return s.length > max ? s.slice(0, max - 1) + '...' : s; }
function buildLocalProject(status = {}, manifest = {}) {
  const identity = manifest.identity || {};
  const listing = manifest.listingMetadata || {};
  const hosting = manifest.hosting || {};
  return {
    name: status.name || identity.name || path.basename(root),
    slug: status.slug || identity.slug || path.basename(root),
    status: status.status || 'active',
    medium: identity.type || status.type || 'tool',
    lifecycle: status.lifecycle || identity.lifecycle || 'active',
    audience: status.audience || identity.audience || 'public-unlaunched',
    type: status.type ? [status.type] : [],
    runtimeUrl: hosting.liveUrl || status.liveUrl || '',
    currentFocus: status.currentFocus || listing.canonicalSummary || '',
    nextMilestone: status.nextMilestone || '',
    summary: listing.canonicalSummary || '',
    localPath: root,
    health: status.health || 'unknown',
  };
}

function buildActions({ revenueReady, preRevenue, rows }) {
  const actions = [];
  if (revenueReady.length === 0) {
    const closest = rows.find((r) => r.stage === 'pre-revenue');
    if (closest) actions.push(`1. Push **${closest.name}** (${closest.readiness}/10) toward revenue-ready by resolving: ${closest.milestone}.`);
  } else {
    actions.push(`1. Focus monetization effort on revenue-ready projects: ${revenueReady.map((r) => r.name).join(', ')}.`);
  }
  if (preRevenue.length) {
    const topPre = preRevenue[0];
    actions.push(`${actions.length + 1}. Closest to revenue-ready: **${topPre.name}** — accelerate to public launch.`);
  }
  const withRuntime = rows.filter((r) => r.runtimeUrl && r.audience === 'public-unlaunched');
  if (withRuntime.length) {
    actions.push(`${actions.length + 1}. ${withRuntime.length} deployed product(s) are public-unlaunched — marketing/launch push would unlock revenue potential.`);
  }
  if (!actions.length) actions.push('1. Continue building — no projects are close to revenue yet.');
  return actions;
}
