#!/usr/bin/env node

/**
 * render-weekly-digest.mjs
 *
 * Generates portfolio/WEEKLY_DIGEST.md from live project truth surfaces.
 * Replaces the old mechanical commit-count workflow with actionable intelligence:
 *   - Task velocity per project (TASK_BOARD completed/active items)
 *   - SIL trajectory and health signals
 *   - Blocker and contradiction rollup
 *   - Lifecycle distribution snapshot
 *
 * Run: node scripts/render-weekly-digest.mjs
 * CI:  called by .github/workflows/weekly-digest.yml
 */

import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'portfolio', 'PROJECT_REGISTRY.json'), 'utf8'));
const today = new Date().toISOString().slice(0, 10);

const activeProjects = registry.projects.filter((p) => p.status !== 'archived');
const appliedProjects = activeProjects.filter((p) => p.studioOsApplied);

// Read project-level data
const rows = appliedProjects.map((project) => {
  const status = readJson(path.join(project.localPath ?? '', 'context', 'PROJECT_STATUS.json'));
  const taskBoard = readText(path.join(project.localPath ?? '', 'context', 'TASK_BOARD.md'));
  const truthAudit = readText(path.join(project.localPath ?? '', 'context', 'TRUTH_AUDIT.md'));

  const nowItems = countPattern(taskBoard, /^## Now\b/, /^## (?:Next|Blocked|Later|Completed|Human|Archived)/, /^- \[ \]/);
  const completedItems = (taskBoard.match(/^- \[x\]/gm) || []).length;
  const blockers = Array.isArray(status?.blockers) ? status.blockers : [];
  const contradictions = extractContradictions(truthAudit);
  const silScore = num(status?.silScore);
  const silAvg3 = num(status?.silAvg3);
  const silVelocity = num(status?.silVelocity);
  const ignisScore = num(status?.ignisScore);

  return {
    name: project.name,
    slug: project.slug,
    lifecycle: project.lifecycle ?? '—',
    audience: project.audience ?? '—',
    health: status?.health ?? project.health ?? 'unknown',
    silScore,
    silAvg3,
    silVelocity,
    ignisScore,
    ignisGrade: status?.ignisGrade ?? null,
    nowItems,
    completedItems,
    blockerCount: blockers.length,
    contradictionCount: contradictions.length,
    truthStatus: status?.truthAuditStatus ?? extractScalar(truthAudit, /^Overall status:\s*(.+)$/m) ?? 'unknown',
    focus: status?.currentFocus ?? project.currentFocus ?? '—',
    milestone: status?.nextMilestone ?? project.nextMilestone ?? '—',
    lastUpdated: status?.lastUpdated ?? null,
  };
});

// Lifecycle distribution
const lifecycleCounts = {};
for (const p of activeProjects) {
  const lc = p.lifecycle ?? 'unknown';
  lifecycleCounts[lc] = (lifecycleCounts[lc] || 0) + 1;
}

// Portfolio stats
const avgSil = average(rows.map((r) => r.silScore).filter((v) => v != null));
const avgIgnis = average(rows.map((r) => r.ignisScore).filter((v) => v != null));
const totalBlockers = rows.reduce((s, r) => s + r.blockerCount, 0);
const totalContradictions = rows.reduce((s, r) => s + r.contradictionCount, 0);
const totalNow = rows.reduce((s, r) => s + r.nowItems, 0);
const totalCompleted = rows.reduce((s, r) => s + r.completedItems, 0);
const ciHealth = loadCiHealth();

// Momentum table — sorted by SIL ascending (lowest momentum first)
const momentumRows = [...rows]
  .filter((r) => r.silScore != null)
  .sort((a, b) => (a.silScore ?? 0) - (b.silScore ?? 0));

// Watchlist — projects with blockers or low health
const watchlist = rows.filter((r) => r.blockerCount > 0 || r.health === 'yellow' || r.health === 'red' || r.truthStatus === 'red');

// Build output
const lines = [
  '# Studio Weekly Digest',
  '',
  `Generated by \`scripts/render-weekly-digest.mjs\` from live project truth surfaces.`,
  `Purpose: weekly portfolio velocity and health intelligence for the Studio Owner.`,
  '',
  '---',
  '',
  `## Week of ${today}`,
  '',
  '### Portfolio Pulse',
  '',
  `> **${appliedProjects.length}/${activeProjects.length}** projects on Studio OS | `,
  `> Avg SIL: **${fmt(avgSil, 1)}/500** | Avg IGNIS: **${fmtLarge(avgIgnis)}** | `,
  `> Open blockers: **${totalBlockers}** | Contradiction debt: **${totalContradictions}** | `,
  `> Task velocity: **${totalCompleted}** completed / **${totalNow}** active Now items`,
  '',
  '### Lifecycle Distribution',
  '',
  `| Stage | Count |`,
  `|---|---:|`,
  ...Object.entries(lifecycleCounts).sort(([, a], [, b]) => b - a).map(([stage, count]) => `| ${stage} | ${count} |`),
  '',
  '### Project Velocity Table',
  '',
  '| Project | Health | SIL | Avg3 | Vel | IGNIS | Now | Done | Blockers | Truth | Focus |',
  '|---|---|---:|---:|---:|---:|---:|---:|---:|---|---|',
  ...momentumRows.map((r) =>
    `| ${r.name} | ${r.health} | ${r.silScore ?? '—'} | ${fmt(r.silAvg3, 1)} | ${r.silVelocity ?? '—'} | ${fmtLarge(r.ignisScore)} | ${r.nowItems} | ${r.completedItems} | ${r.blockerCount} | ${r.truthStatus} | ${truncate(r.focus, 60)} |`
  ),
  '',
  '### Attention Watchlist',
  '',
  ...(watchlist.length
    ? watchlist.map((r) => `- **${r.name}** — health: ${r.health}, truth: ${r.truthStatus}, blockers: ${r.blockerCount}, contradictions: ${r.contradictionCount}`)
    : ['- No projects require immediate attention.']),
  '',
  '### CI Red',
  '',
  ...buildCiRedSection(ciHealth),
  '',
  '### Recommended Actions',
  '',
  ...buildActions({ totalBlockers, totalContradictions, watchlist, momentumRows }),
  '',
  '---',
  '',
  `*Generated: ${today} | Source: PROJECT_STATUS.json + TASK_BOARD.md + TRUTH_AUDIT.md per repo*`,
  '',
];

fs.writeFileSync(path.join(root, 'portfolio', 'WEEKLY_DIGEST.md'), lines.join('\n'));
console.log(`WEEKLY_DIGEST.md written (${rows.length} projects, ${today})`);

// ── Helpers ────────────────────────────────────────────────────────────────

function readJson(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return null;
  try { return JSON.parse(fs.readFileSync(filePath, 'utf8')); } catch { return null; }
}

function readText(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return '';
  return fs.readFileSync(filePath, 'utf8');
}

function extractScalar(md, pattern) {
  return md.match(pattern)?.[1]?.trim() ?? null;
}

function extractContradictions(md) {
  const section = md.match(/## Contradictions\s+([\s\S]*?)(?=\n##\s+|$)/);
  if (!section) return [];
  return section[1].split(/\r?\n/).map((l) => l.trim()).filter((l) => l.startsWith('- ') && !/^none recorded/i.test(l.slice(2)));
}

function countPattern(text, sectionStart, sectionEnd, linePattern) {
  const lines = text.split(/\r?\n/);
  let inSection = false;
  let count = 0;
  for (const line of lines) {
    if (sectionStart.test(line)) { inSection = true; continue; }
    if (inSection && sectionEnd.test(line)) break;
    if (inSection && linePattern.test(line)) count++;
  }
  return count;
}

function num(v) { const n = Number(v); return Number.isFinite(n) ? n : null; }
function average(vals) { return vals.length ? vals.reduce((s, v) => s + v, 0) / vals.length : null; }
function fmt(v, d = 0) { return v == null ? '—' : Number(v).toFixed(d); }
function fmtLarge(v) { return v == null ? '—' : Math.round(v).toLocaleString(); }
function truncate(s, max) { return s.length > max ? s.slice(0, max - 1) + '...' : s; }

function loadCiHealth() {
  const res = spawnSync(process.execPath, [path.join(root, 'scripts', 'check-ci-health.mjs'), '--json'], {
    cwd: root,
    encoding: 'utf8',
    timeout: 120000,
  });
  try {
    return JSON.parse(res.stdout || '{}');
  } catch {
    return { error: 'CI health unavailable', totalAlerts: null, results: [] };
  }
}

function buildCiRedSection(report) {
  if (report.error) return [`- ${report.error}. Run \`node scripts/ops.mjs ci-health --json\` locally for details.`];
  const alerts = (report.results || []).flatMap(r => (r.alerts || []).map(a => ({ ...a, slug: r.slug, repo: r.repo })));
  if (!alerts.length) return ['- No consistently failing workflows detected.'];
  const lines = [
    `> **${alerts.length}** workflow(s) with repeated failures across **${report.reposScanned ?? '?'}** scanned repos.`,
    '',
    '| Repo | Workflow | Failed | Total | Fail% | Last Run |',
    '|---|---|---:|---:|---:|---|',
  ];
  for (const alert of alerts.sort((a, b) => b.failed - a.failed).slice(0, 12)) {
    lines.push(`| ${alert.slug} | ${alert.workflow} | ${alert.failed} | ${alert.total} | ${alert.failRate}% | ${alert.lastRun} |`);
  }
  if (alerts.length > 12) lines.push(`| ... | ${alerts.length - 12} more |  |  |  |  |`);
  return lines;
}

function buildActions({ totalBlockers, totalContradictions, watchlist, momentumRows }) {
  const actions = [];
  if (totalBlockers > 0) actions.push(`1. Clear ${totalBlockers} active blocker(s) — these directly limit project velocity.`);
  if ((ciHealth.totalAlerts ?? 0) > 0) actions.push(`${actions.length + 1}. Triage ${ciHealth.totalAlerts} CI Red workflow alert(s) — see CI Red section above.`);
  if (totalContradictions > 3) actions.push(`${actions.length + 1}. Reduce contradiction debt (${totalContradictions} total) — founder-facing reporting accuracy depends on this.`);
  if (momentumRows.length && momentumRows[0].silScore != null && momentumRows[0].silScore < 38) {
    actions.push(`${actions.length + 1}. Prioritize lowest-SIL project: **${momentumRows[0].name}** (${momentumRows[0].silScore}/500).`);
  }
  if (watchlist.length > 3) actions.push(`${actions.length + 1}. ${watchlist.length} projects on the watchlist — schedule dedicated sessions for the worst 2.`);
  if (!actions.length) actions.push('1. Portfolio is healthy — focus on highest-priority milestones.');
  return actions;
}
